package io.miragon.bpmn.adapter.outbound.codegen.builder.typescript

import freemarker.template.SimpleScalar
import freemarker.template.TemplateHashModel
import freemarker.template.TemplateModel
import io.miragon.bpmn.adapter.outbound.codegen.SharedDefinitionType
import io.miragon.bpmn.adapter.outbound.codegen.SourceCode
import io.miragon.bpmn.adapter.outbound.codegen.builder.typescript.TypeScriptSyntax.identifier
import io.miragon.bpmn.adapter.outbound.codegen.freemarker.TemplateRenderer

/**
 * A generated TypeScript module, whose imports are only known once its body is rendered, e.g.
 * ```
 * // Generated by bpmn-to-code
 * import * as Runtime from "@miragon/bpmn-to-code-runtime";
 * import { Messages } from "./Messages.js";
 *
 * export class EventContractSigned implements Runtime.Event, Runtime.HasSuccessors, Runtime.MessageEvent { … }
 * ```
 * The runtime package is imported as `Runtime`, type-only while the body uses none of its values. Templates read its
 * names through [runtimeTypes] and [runtimeValues], e.g. `${runtimeTypes.FlowNode}`, so every use is recorded. Imports
 * end in `.js`, which resolves under both `nodenext` and `bundler` module resolution.
 */
internal class TypeScriptSourceFile {

    private val sharedDefinitions = sortedSetOf<String>()
    private var runtimeImport = RuntimeImport.NONE

    val runtimeTypes: TemplateHashModel = RuntimeNames { runtimeType(it) }

    val runtimeValues: TemplateHashModel = RuntimeNames { runtimeValue(it) }

    /**
     * e.g. `Runtime.HasSuccessors`
     */
    fun runtimeType(name: String): String {
        if (runtimeImport == RuntimeImport.NONE) {
            runtimeImport = RuntimeImport.TYPE
        }
        return "$RUNTIME_ALIAS.$name"
    }

    /**
     * e.g. `Runtime.sequenceFlows`
     */
    fun runtimeValue(name: String): String {
        runtimeImport = RuntimeImport.VALUE
        return "$RUNTIME_ALIAS.$name"
    }

    /**
     * e.g. `Messages.MIRAVELO_CONTRACT_SIGNED`
     */
    fun sharedReference(type: SharedDefinitionType, constantName: String): String {
        sharedDefinitions += type.typeName
        return "${type.typeName}.${identifier(constantName)}"
    }

    fun render(templateName: String, model: Any): SourceCode {
        val body = TemplateRenderer.render(templateName = templateName, model = model)
        val wrapped = TemplateRenderer.render(
            templateName = "typescript/source-file.ftl",
            model = Wrapper(runtimeImport = runtimeImport, sharedDefinitions = sharedDefinitions.toList(), body = body),
        )
        return SourceCode(wrapped)
    }

    data class Wrapper(val runtimeImport: RuntimeImport, val sharedDefinitions: List<String>, val body: String)

    enum class RuntimeImport { NONE, TYPE, VALUE }

    private class RuntimeNames(private val reference: (String) -> String) : TemplateHashModel {

        override fun get(key: String): TemplateModel = SimpleScalar(reference(key))

        override fun isEmpty(): Boolean = false
    }

    companion object {
        const val RUNTIME_ALIAS = "Runtime"
    }
}
