const scene = inject("landing-scene", ref(0))
const moving = inject("landing-moving", ref(false))
const advancing = inject("landing-advancing", ref(false))
const sceneProgress = inject("landing-scene-progress", ref(0))
const sceneCount = inject("landing-scene-count", scenes.length)
const current = computed(() => scenes[scene.value])

const TYPE_MS = 18
const SHOW_MS = 160
const START_MS = 250
const POPUP_MS = 1100
const RUN_MS = 350
const HOLD_MS = 1200

type Step = { pane: number; line: number }
const animated = computed(() =>
  current.value.panes.flatMap((pane, paneIndex) =>
    pane.lines.flatMap((line, lineIndex) => (line.enter ? [{ pane: paneIndex, line: lineIndex }] : [])),
  ),
)

// Where the scene stands: animated lines before `done` are complete, the one at `done` shows `chars` characters.
const done = ref(Number.MAX_SAFE_INTEGER)
const chars = ref(0)
const popup = ref(false)
const runCount = ref(Number.MAX_SAFE_INTEGER)

function plainLength(text: string) {
  return text.replace(/\[\[|\]\]|\*\*|~/g, "").length
}

function lineState(paneIndex: number, lineIndex: number): "full" | "partial" | "hidden" {
  const position = animated.value.findIndex((step) => step.pane === paneIndex && step.line === lineIndex)
  if (position === -1 || position < done.value) return "full"
  return position === done.value ? "partial" : "hidden"
}

function sceneLength(sceneValue: Scene) {
  const lines = sceneValue.panes.flatMap((pane) => pane.lines).filter((line) => line.enter)
  const typing = lines.reduce((total, line) => {
    if (line.enter === "show") return total + SHOW_MS
    return total + plainLength(line.text) * TYPE_MS + (line.pauseAt === undefined ? 0 : POPUP_MS)
  }, 0)
  const results = sceneValue.panes.find((pane) => pane.run)?.run?.length ?? 0
  const run = results * RUN_MS
  return START_MS + typing + run + HOLD_MS
}

let timer: ReturnType<typeof setTimeout> | undefined
const after = (ms: number, step: () => void) => {
  timer = setTimeout(step, ms)
}

function showEndState() {
  clearTimeout(timer)
  done.value = Number.MAX_SAFE_INTEGER
  popup.value = false
  runCount.value = Number.MAX_SAFE_INTEGER
  stopProgress()
}

function play() {
  clearTimeout(timer)
  done.value = 0
  chars.value = 0
  popup.value = false
  runCount.value = 0
  startProgress(sceneLength(current.value))
  after(START_MS, advanceLine)
}

function advanceLine() {
  const step = animated.value[done.value]
  if (!step) return after(RUN_MS, showRun)
  const line = current.value.panes[step.pane].lines[step.line]
  if (line.enter === "show") {
    done.value += 1
    return after(SHOW_MS, advanceLine)
  }
  typeLine(line)
}

function typeLine(line: Line) {
  if (chars.value === line.pauseAt && !popup.value) {
    popup.value = true
    return after(POPUP_MS, () => {
      chars.value = plainLength(line.text)
      popup.value = false
      typeLine(line)
    })
  }
  if (chars.value < plainLength(line.text)) {
    chars.value += 1
    return after(TYPE_MS, () => typeLine(line))
  }
  done.value += 1
  chars.value = 0
  advanceLine()
}

function showRun() {
  const results = current.value.panes.find((pane) => pane.run)?.run?.length ?? 0
  if (runCount.value < results) {
    runCount.value += 1
    return after(RUN_MS, showRun)
  }
  after(HOLD_MS, finishScene)
}

// The progress line under the active step follows the scene as it plays, and stands still on Pause.
let frame = 0
function startProgress(duration: number) {
  cancelAnimationFrame(frame)
  const start = performance.now()
  const tick = (now: number) => {
    sceneProgress.value = Math.min((now - start) / duration, 1)
    if (sceneProgress.value < 1) frame = requestAnimationFrame(tick)
  }
  sceneProgress.value = 0
  frame = requestAnimationFrame(tick)
}
function stopProgress() {
  cancelAnimationFrame(frame)
}

function finishScene() {
  if (advancing.value) scene.value = (scene.value + 1) % sceneCount
  else if (moving.value) after(500, finishScene)
}

watch(scene, () => (moving.value ? play() : showEndState()))
watch(moving, (on) => (on ? play() : showEndState()))
onMounted(() => {
  if (moving.value) play()
})
onBeforeUnmount(() => {
  clearTimeout(timer)
  stopProgress()
})

type Part = { kind: "plain" | "api" | "frame" | "quiet"; text: string }
function parts(text: string): Part[] {
  return text
    .split(/(\[\[.*?\]\]|\*\*.*?\*\*|~.*?~)/)
    .filter(Boolean)
    .map((piece): Part => {
      if (piece.startsWith("[[")) return { kind: "frame", text: piece.slice(2, -2).replaceAll("**", "") }
      if (piece.startsWith("**")) return { kind: "api", text: piece.slice(2, -2) }
      if (piece.startsWith("~")) return { kind: "quiet", text: piece.slice(1, -1) }
      return { kind: "plain", text: piece }
    })
}

function isEntering(paneIndex: number, lineIndex: number) {
  const line = current.value.panes[paneIndex].lines[lineIndex]
  return line.enter === "show" && lineState(paneIndex, lineIndex) !== "full"
}

function visibleParts(text: string, paneIndex: number, lineIndex: number): Part[] {
  const state = lineState(paneIndex, lineIndex)
  if (state === "full" || isEntering(paneIndex, lineIndex)) return parts(text)
  if (state === "hidden") return []
  let left = chars.value
  return parts(text).flatMap((part) => {
    const shown = part.text.slice(0, Math.max(left, 0))
    left -= part.text.length
    return shown ? [{ ...part, text: shown }] : []
  })
}
